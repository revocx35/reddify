#!/usr/bin/env python3
"""Regenerates ../reddify_android/app/.../ui/theme/Icons.kt from web/src/components/Icon.tsx (one icon set for both clients)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "web/src/components/Icon.tsx").read_text()
block = src[src.index("const PATHS"):src.index("};", src.index("const PATHS"))]
entries = re.findall(r"^\s+(\w+):\s*\n?\s*'([^']+)'", block, re.M)
out = ["package io.github.revocx35.reddify.ui.theme", "",
       "import androidx.compose.ui.graphics.PathFillType", "import androidx.compose.ui.graphics.SolidColor",
       "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.graphics.vector.ImageVector",
       "import androidx.compose.ui.graphics.vector.PathParser", "import androidx.compose.ui.unit.dp", "",
       "// GENERATED by scripts/gen-android-icons.py from web/src/components/Icon.tsx: do not edit by hand.", "",
       "private fun icon(name: String, d: String): ImageVector = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f)",
       "    .addPath(PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.White), pathFillType = PathFillType.EvenOdd)",
       "    .build()", "", "object RIcons {"]
for name, d in entries:
    out.append(f'    val {name}: ImageVector by lazy {{ icon("{name}", "{d}") }}')
out.append("}")
(root.parent / "reddify_android/app/src/main/java/io/github/revocx35/reddify/ui/theme/Icons.kt").write_text("\n".join(out) + "\n")
print(f"{len(entries)} icons")
